from pydantic import BaseModel, Field
from typing import List, Optional

class CheckRequest(BaseModel):
    question: str = Field(..., description="The factual question asked to models")
    answer_a: str = Field(..., description="Response generated by Model A")
    answer_b: str = Field(..., description="Response generated by Model B")
    model_a_name: Optional[str] = Field("Model A", description="Name of Model A")
    model_b_name: Optional[str] = Field("Model B", description="Name of Model B")

class VoteRequest(BaseModel):
    model_a: str
    model_b: str
    winner: str

class ClaimDetail(BaseModel):
    claim: str
    verdict: str
    score: float
    reasoning: str
    evidence: Optional[List[dict]] = None

class GroundingResult(BaseModel):
    grounding_score: float
    claims_analyzed: int
    claims_supported: int
    claims_refuted: int
    details: List[ClaimDetail]

class JudgeResult(BaseModel):
    winner: str
    confidence: float
    reasoning: str

class LeaderboardItem(BaseModel):
    model: str
    elo: float
